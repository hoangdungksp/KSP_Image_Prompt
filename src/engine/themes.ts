/**
 * KSP Image - Themes Catalog
 *
 * 12 categories with ~120 sub-themes total.
 * Each theme provides:
 * - Vietnamese description (idea.raw)
 * - Pre-translated English (avoids API call for these)
 * - Recommended camera style (BOKEH or DOCUMENTARY)
 * - Time/lighting hint
 * - Mood tags
 *
 * Free-form ideas typed by users still get translated via Gemini API.
 */

import type { CameraStyle } from "../types";
import { ADDITIONAL_THEMES } from "./themesAdditional";


export interface ThemePreset {
  id: string;
  category: string;
  name: string;
  /** Vietnamese description (what user sees) */
  description: string;
  /** Pre-translated EN (used in prompt assembly) */
  descriptionEn: string;
  /** Recommended camera style */
  cameraStyle: CameraStyle;
  /** Time / lighting */
  time?:
    | "golden_hour"
    | "blue_hour"
    | "midday"
    | "afternoon"
    | "night"
    | "overcast"
    | "indoor";
  /** Mood tags */
  mood?: string[];
  /** Emoji for UI */
  emoji: string;
  /** NEW v0.5: which mode this theme is designed for (defaults to "lifestyle" for old themes) */
  mode?: "lifestyle" | "tvc_commercial" | "product_photo" | "editorial_fashion";
  /** NEW v0.5: which industry this theme belongs to (defaults to "travel" for old themes) */
  industry?: "skincare" | "fnb" | "tech" | "fashion" | "travel" | "general";
}

export interface ThemeCategory {
  id: string;
  name: string;
  emoji: string;
  description: string;
}

