import { INDUSTRY_THEMES } from "./themes_industry";

/**
 * Auto-tag legacy themes (BASE + ADDITIONAL) with industry="travel" mode="lifestyle"
 * if they don't already have these fields. This ensures backward compat —
 * old themes still work and become part of "Travel/Lifestyle" industry.
 */
function autoTagLegacy(themes: ThemePreset[]): ThemePreset[] {
  return themes.map((t) => ({
    ...t,
    industry: t.industry || "travel",
    mode: t.mode || "lifestyle",
  }));
}

const LEGACY_THEMES = autoTagLegacy([...BASE_THEMES, ...ADDITIONAL_THEMES]);

export const THEMES: ThemePreset[] = [...LEGACY_THEMES, ...INDUSTRY_THEMES];

// ============================================================================
// HELPERS
// ============================================================================

export function getThemesByCategory(categoryId: string): ThemePreset[] {
  return THEMES.filter((t) => t.category === categoryId);
}

export function searchThemes(query: string): ThemePreset[] {
  const q = query.toLowerCase().trim();
  if (!q) return THEMES;
  return THEMES.filter(
    (t) =>
      t.name.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.descriptionEn.toLowerCase().includes(q) ||
      t.category.toLowerCase().includes(q)
  );
}

export function getThemeById(id: string): ThemePreset | undefined {
  return THEMES.find((t) => t.id === id);
}
